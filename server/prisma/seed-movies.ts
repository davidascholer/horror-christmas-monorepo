/**
 * Seed movies into the database
 */
async function seedMovies() {
  console.log('🎬 Starting movie seed...\n');

  // Get franchise IDs first
  const franchises = await prisma.franchise.findMany();
  const franchiseMap = new Map(franchises.map(f => [f.slug, f.id]));

  // Get tag IDs
  const tags = await prisma.tag.findMany();
  const tagMap = new Map(tags.map(t => [t.slug, t.id]));

  const createdMovies = new Map<string, string>();

  for (const movie of movies) {
    // Get franchise ID if specified
    const franchiseId = movie.franchiseSlug 
      ? franchiseMap.get(movie.franchiseSlug)
      : undefined;

    if (movie.franchiseSlug && !franchiseId) {
      console.warn(`⚠ Warning: Franchise not found: ${movie.franchiseSlug}`);
    }

    const created = await prisma.movie.upsert({
      where: { slug: movie.slug },
      update: {
        title: movie.title,
        mediaType: movie.mediaType,
        synopsis: movie.synopsis,
        originalTitle: movie.originalTitle,
        releaseYear: movie.releaseYear,
        releaseDate: movie.releaseDate ? new Date(movie.releaseDate) : undefined,
        runtime: movie.runtime,
        poster: movie.poster,
        hero: movie.hero,
        trailerUrl: movie.trailerUrl,
        seoTitle: movie.seoTitle,
        seoDescription: movie.seoDescription,
        featured: movie.featured,
        franchiseId: franchiseId,
      },
      create: {
        slug: movie.slug,
        title: movie.title,
        mediaType: movie.mediaType,
        synopsis: movie.synopsis,
        originalTitle: movie.originalTitle,
        releaseYear: movie.releaseYear,
        releaseDate: movie.releaseDate ? new Date(movie.releaseDate) : undefined,
        runtime: movie.runtime,
        poster: movie.poster,
        hero: movie.hero,
        trailerUrl: movie.trailerUrl,
        seoTitle: movie.seoTitle,
        seoDescription: movie.seoDescription,
        featured: movie.featured,
        franchiseId: franchiseId,
        status: 'DRAFT', // Will be published after relationships are set up
      },
    });

    createdMovies.set(movie.slug, created.id);

    // Delete existing tag relationships and recreate
    await prisma.movieTag.deleteMany({
      where: { movieId: created.id },
    });

    // Create tag relationships
    for (const tagSlug of movie.tagSlugs) {
      const tagId = tagMap.get(tagSlug);
      if (tagId) {
        await prisma.movieTag.create({
          data: {
            movieId: created.id,
            tagId: tagId,
          },
        });
      }
    }

    console.log(`✓ Upserted: ${movie.title} (${movie.releaseYear})`);
  }

  console.log(`\n✅ Movie seed complete! Created ${createdMovies.size} movies.\n`);

  // Statistics
  const mediaTypeBreakdown = new Map<string, number>();
  const franchiseBreakdown = new Map<string, number>();
  
  for (const movie of movies) {
    mediaTypeBreakdown.set(
      movie.mediaType,
      (mediaTypeBreakdown.get(movie.mediaType) || 0) + 1
    );
    
    if (movie.franchiseSlug) {
      franchiseBreakdown.set(
        movie.franchiseSlug,
        (franchiseBreakdown.get(movie.franchiseSlug) || 0) + 1
      );
    }
  }

  console.log('📊 Statistics:');
  console.log('   Media Types:');
  for (const [type, count] of mediaTypeBreakdown.entries()) {
    console.log(`     ${type}: ${count}`);
  }
  
  console.log('\n   Franchise Distribution:');
  for (const [franchise, count] of franchiseBreakdown.entries()) {
    console.log(`     ${franchise}: ${count}`);
  }
  
  const featuredCount = movies.filter(m => m.featured).length;
  console.log(`\n   Featured Movies: ${featuredCount}`);
  console.log(`   Total Movies: ${movies.length}\n`);

  return createdMovies;
}

/**
 * Main execution
 */
async function main() {
  try {
    await seedMovies();
  } catch (error) {
    console.error('❌ Seed failed:', error);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
}

// Only self-execute when run directly (e.g. `tsx prisma/seed-x.ts`), never on
